"""Generate openapi.yaml and template.yaml from api/routes.yaml and api/template.base.yaml.

openapi.yaml is built entirely from api/routes.yaml. template.yaml is api/template.base.yaml
(tables, bucket, layers, API settings, outputs) with the Lambda functions and their API
permissions, which come from api/routes.yaml, spliced in at the marker line.

    python scripts/gen_api.py                   write both files to the repo root
    python scripts/gen_api.py --out-dir DIR     write them to DIR instead
    python scripts/gen_api.py --check           fail if the files in the repo root are stale
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ROUTES_PATH = ROOT / "api" / "routes.yaml"
BASE_PATH = ROOT / "api" / "template.base.yaml"
OUTPUT_NAMES = ("openapi.yaml", "template.yaml")

MARKER = "# @@generated-functions@@"
HEADER = "# Generated by scripts/gen_api.py from api/. Do not edit by hand.\n"

HTTP_METHODS = ("get", "post", "put", "delete")
SCALARS = ("string", "number", "boolean", "integer")
POLICIES = {
    "crud": ("DynamoDBCrudPolicy", "TableName"),
    "read": ("DynamoDBReadPolicy", "TableName"),
    "s3crud": ("S3CrudPolicy", "BucketName"),
    "s3read": ("S3ReadPolicy", "BucketName"),
}

ALLOW_ORIGIN = "method.response.header.Access-Control-Allow-Origin"
ALLOW_METHODS = "method.response.header.Access-Control-Allow-Methods"
ALLOW_HEADERS = "method.response.header.Access-Control-Allow-Headers"
CORS_HEADERS = "'Content-Type,X-Amz-Date,Authorization,X-Api-Key,X-Amz-Security-Token'"
QUOTE_FIX = r""".replaceAll("\\'","'")"""
GATEWAY_LOCATION = {"path": "path", "query": "querystring"}
PATH_PARAM = re.compile(r"\{(\w+)\+?\}")


def _escaped(name: str) -> str:
    return f"$util.escapeJavaScript($input.params('{name}'))" + QUOTE_FIX


def request_template(params: list[tuple[str, bool]]) -> str:
    """Mapping template that turns request parameters (name, optional) into the JSON event.

    Optional parameters are written first, each inside an #if block that drops it when empty.
    """
    required = [name for name, optional in params if not optional]
    if not required:
        raise ValueError("a request template needs at least one required parameter")
    lines = ["{"]
    for name, optional in params:
        if optional:
            lines += [
                f"#if($input.params('{name}') != \"\")",
                f'  "{name}": "{_escaped(name)}",',
                "#end",
            ]
    lines += [f'  "{name}": "{_escaped(name)}"' for name in required]
    for i in range(len(lines) - len(required), len(lines) - 1):
        lines[i] += ","
    return "\n".join([*lines, "}"])


def _parse_query(text: str) -> tuple[str, str | None, bool]:
    name, _, fmt = text.removesuffix("?").partition(":")
    return name, fmt or None, text.endswith("?")


def _string_schema(fmt: str | None) -> dict:
    return {"type": "string", **({"format": fmt} if fmt else {})}


def _ok_response(*extra_headers: str) -> dict:
    headers = {"Access-Control-Allow-Origin": {"schema": {"type": "string"}}}
    headers |= {name: {"schema": {"type": "string"}} for name in extra_headers}
    return {
        "200": {
            "description": "200 response",
            "headers": headers,
            "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Empty"}}},
        }
    }


def _operation(path: str, route: dict) -> dict:
    query = [_parse_query(text) for text in route.get("query", [])]
    path_params = PATH_PARAM.findall(path)
    parameters = [
        {"name": name, "in": "path", "required": True, "schema": {"type": "string"}}
        for name in path_params
    ]
    parameters += [
        {
            "name": name,
            "in": "query",
            **({} if optional else {"required": True}),
            "schema": _string_schema(fmt),
        }
        for name, fmt, optional in query
    ]
    integration = {
        "type": "aws",
        "uri": {
            "Fn::Sub": "arn:aws:apigateway:${AWS::Region}:lambda:path/2015-03-31/functions/"
            f"${{{route['fn']}Function.Arn}}/invocations"
        },
        "httpMethod": "POST",
        "responses": {
            "default": {"statusCode": "200", "responseParameters": {ALLOW_ORIGIN: "'*'"}}
        },
    }
    if parameters:
        integration["requestParameters"] = {
            f"integration.request.{GATEWAY_LOCATION[param['in']]}.{param['name']}": (
                f"method.request.{GATEWAY_LOCATION[param['in']]}.{param['name']}"
            )
            for param in parameters
        }
        integration["requestTemplates"] = {
            "application/json": request_template(
                [(name, False) for name in path_params]
                + [(name, optional) for name, _, optional in query]
            )
        }
    else:
        integration["requestTemplates"] = {"application/json": "$input.body"}
    integration |= {
        "passthroughBehavior": "when_no_match",
        "timeoutInMillis": 29000,
        "contentHandling": "CONVERT_TO_TEXT",
        **route.get("integration", {}),
    }
    operation = {"operationId": route["op"]}
    if parameters:
        operation["parameters"] = parameters
    if "body" in route:
        ref = f"#/components/schemas/{route['body']}"
        operation["requestBody"] = {
            "content": {"application/json": {"schema": {"$ref": ref}}},
            "required": True,
        }
    operation["responses"] = _ok_response()
    operation["security"] = [{"api_key": []}]
    operation["x-amazon-apigateway-integration"] = integration
    return operation


def _options_operation(path: str, methods: list[str]) -> dict:
    allowed = ",".join(sorted(method.upper() for method in [*methods, "options"]))
    operation = {}
    path_params = PATH_PARAM.findall(path)
    if path_params:
        operation["parameters"] = [
            {"name": name, "in": "path", "required": True, "schema": {"type": "string"}}
            for name in path_params
        ]
    operation["responses"] = _ok_response(
        "Access-Control-Allow-Methods", "Access-Control-Allow-Headers"
    )
    operation["x-amazon-apigateway-integration"] = {
        "type": "mock",
        "responses": {
            "default": {
                "statusCode": "200",
                "responseParameters": {
                    ALLOW_METHODS: f"'{allowed}'",
                    ALLOW_HEADERS: CORS_HEADERS,
                    ALLOW_ORIGIN: "'*'",
                },
            }
        },
        "requestTemplates": {"application/json": '{"statusCode": 200}'},
        "passthroughBehavior": "when_no_match",
    }
    return operation


def _field_schema(field_type) -> dict:
    if isinstance(field_type, dict):
        return dict(field_type)
    if field_type.endswith("[]"):
        ref = f"#/components/schemas/{field_type.removesuffix('[]')}"
        return {"type": "array", "items": {"$ref": ref}}
    if field_type in SCALARS:
        return {"type": field_type}
    raise ValueError(f"unknown field type: {field_type!r}")


def _model_schema(name: str, fields: dict, fragments: dict) -> dict:
    properties = {}
    for field, field_type in fields.items():
        if field.startswith("+"):
            for fragment_field, fragment_type in fragments[field.removeprefix("+")].items():
                properties[fragment_field] = _field_schema(fragment_type)
        else:
            properties[field] = _field_schema(field_type)
    return {"title": name, "type": "object", "properties": properties}


def _functions(spec: dict) -> dict[str, dict]:
    """Function name -> settings (with `dir` added and the folder's `_defaults` applied)."""
    functions = {}
    for folder, entries in spec["functions"].items():
        defaults = entries.get("_defaults", {})
        for name, settings in entries.items():
            if name != "_defaults":
                functions[name] = {**defaults, **settings, "dir": folder}
    return functions


def check_spec(spec: dict) -> None:
    functions = _functions(spec)
    used = set()
    for path, route in spec["routes"].items():
        for method, operation in route.items():
            if method not in HTTP_METHODS:
                raise ValueError(f"{path}: unsupported method {method!r}")
            if operation["fn"] not in functions:
                raise ValueError(f"{method} {path}: unknown function {operation['fn']!r}")
            if "body" in operation and operation["body"] not in spec["models"]:
                raise ValueError(f"{method} {path}: unknown model {operation['body']!r}")
            if ("body" in operation) == (method == "get"):
                raise ValueError(f"{method} {path}: a body goes with every method but get")
            used.add(operation["fn"])
    if unused := sorted(set(functions) - used):
        raise ValueError(f"functions without a route: {', '.join(unused)}")
    for name, settings in functions.items():
        for policy in settings["policies"]:
            if policy.split()[0] not in POLICIES:
                raise ValueError(f"{name}: unknown policy {policy!r}")


def build_openapi(spec: dict) -> dict:
    paths = {}
    for path, route in spec["routes"].items():
        paths[path] = {method: _operation(path, route[method]) for method in route}
        paths[path]["options"] = _options_operation(path, list(route))
    schemas = {
        name: _model_schema(name, fields, spec["fragments"])
        for name, fields in spec["models"].items()
    }
    schemas["Empty"] = {"title": "Empty Schema", "type": "object"}
    return {
        "openapi": "3.0.1",
        "info": {"title": "Fiscus API", "version": "1.0"},
        "x-amazon-apigateway-api-key-source": "HEADER",
        "paths": paths,
        "components": {
            "schemas": schemas,
            "securitySchemes": {"api_key": {"type": "apiKey", "name": "x-api-key", "in": "header"}},
        },
    }


def _function_block(name: str, settings: dict) -> str:
    lines = [
        f"  {name}Function:",
        "    Type: AWS::Serverless::Function",
        "    Properties:",
        f"      CodeUri: lambda/{settings['dir']}/",
        f"      Handler: {name}.lambda_handler",
    ]
    if "timeout" in settings:
        lines.append(f"      Timeout: {settings['timeout']}")
    if settings.get("layers"):
        lines.append("      Layers:")
        lines += [f"        - !Ref {layer}" for layer in settings["layers"]]
    lines.append("      Policies:")
    for policy in settings["policies"]:
        kind, resource = policy.split()
        policy_name, parameter = POLICIES[kind]
        lines += [f"        - {policy_name}:", f"            {parameter}: !Ref {resource}"]
    return "\n".join(lines)


def _permission_block(name: str) -> str:
    return "\n".join(
        [
            f"  {name}ApiPermission:",
            "    Type: AWS::Lambda::Permission",
            "    Properties:",
            "      Action: lambda:InvokeFunction",
            f"      FunctionName: !Ref {name}Function",
            "      Principal: apigateway.amazonaws.com",
            '      SourceArn: !Sub "arn:${AWS::Partition}:execute-api:${AWS::Region}'
            ':${AWS::AccountId}:${Api}/*"',
        ]
    )


def build_template(spec: dict, base: str) -> str:
    functions = _functions(spec)
    blocks = [_function_block(name, settings) for name, settings in functions.items()]
    blocks += [_permission_block(name) for name in functions]
    if base.count(MARKER) != 1:
        raise ValueError(f"{BASE_PATH.name} must contain the line {MARKER!r} exactly once")
    return base.replace(MARKER, "\n\n".join(blocks))


def _dump(document: dict) -> str:
    return yaml.safe_dump(
        document, sort_keys=False, width=10**6, allow_unicode=True, default_flow_style=False
    )


def build(routes_path: Path = ROUTES_PATH, base_path: Path = BASE_PATH) -> dict[str, str]:
    """File name -> generated text, for every generated file."""
    spec = yaml.safe_load(routes_path.read_text(encoding="utf-8"))
    check_spec(spec)
    base = base_path.read_text(encoding="utf-8")
    return {
        "openapi.yaml": HEADER + _dump(build_openapi(spec)),
        "template.yaml": HEADER + build_template(spec, base),
    }


def stale_files(outputs: dict[str, str], directory: Path) -> list[str]:
    """Names of generated files that are missing from `directory` or differ from `outputs`."""
    stale = []
    for name, text in outputs.items():
        path = directory / name
        if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            stale.append(name)
    return stale


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out-dir", type=Path, default=ROOT, help="where to write the files")
    parser.add_argument("--check", action="store_true", help="fail if the repo root is stale")
    args = parser.parse_args(argv)

    outputs = build()
    if args.check:
        if stale := stale_files(outputs, ROOT):
            print(f"stale: {', '.join(stale)}. Run: python scripts/gen_api.py", file=sys.stderr)
            return 1
        return 0
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in outputs.items():
        (args.out_dir / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {args.out_dir / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
